#!/usr/bin/env node
/**
 * Generates `src/lib/devportal/sdk-manifest.ts` from the real SDK projects in
 * `sdk-source/`. Run after changing any SDK source file:
 *
 *   node scripts/generate-sdk-manifest.mjs
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const SDK_ROOT = join(ROOT, 'sdk-source');
const OUTPUT = join(ROOT, 'src/lib/devportal/sdk-manifest.ts');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile()) out.push(full);
  }
  return out.sort();
}

const manifest = {};
for (const id of readdirSync(SDK_ROOT).sort()) {
  const dir = join(SDK_ROOT, id);
  if (!statSync(dir).isDirectory()) continue;

  const files = walk(dir);
  const hash = createHash('sha256');
  let bytes = 0;
  for (const file of files) {
    const content = readFileSync(file);
    bytes += content.byteLength;
    hash.update(relative(dir, file));
    hash.update(content);
  }

  manifest[id] = { files: files.length, bytes, sha256: hash.digest('hex') };
}

const body = `/**
 * Generated by \`scripts/generate-sdk-manifest.mjs\` — do not edit by hand.
 *
 * Describes the real SDK projects in \`sdk-source/\` that the download endpoint
 * packages on demand. \`sha256\` is a digest of the source tree, so it changes
 * whenever any SDK file changes.
 */

export type SdkArchiveInfo = {
  /** Number of files in the packaged project. */
  files: number;
  /** Total uncompressed size of the source tree, in bytes. */
  bytes: number;
  /** SHA-256 digest of the source tree. */
  sha256: string;
};

export const SDK_ARCHIVES: Record<string, SdkArchiveInfo> = ${JSON.stringify(manifest, null, 2)};

/** Human-readable size for an SDK source tree. */
export function formatBytes(bytes: number): string {
  if (bytes < 1024) return \`\${bytes} B\`;
  if (bytes < 1024 * 1024) return \`\${(bytes / 1024).toFixed(1)} KB\`;
  return \`\${(bytes / (1024 * 1024)).toFixed(2)} MB\`;
}
`;

writeFileSync(OUTPUT, body);
console.log(`Wrote ${relative(ROOT, OUTPUT)} for ${Object.keys(manifest).length} SDKs.`);